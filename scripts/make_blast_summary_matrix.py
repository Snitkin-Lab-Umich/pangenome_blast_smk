
import argparse
import pandas as pd

def read_panaroo_data(panaroo_file, filterfile):
    pan = pd.read_csv(panaroo_file,keep_default_na=False)
    # subset pan to only contain columns for the gene family names and isolates
    pan = pan.loc[:, pan.columns.str.startswith(("Gene", "SRR", "ARR", "DRR", "ERR", "UM_", "Chi_", "b8441"))]
    # subset pan to only include isolates in the filter file, if provided
    if filterfile is not None:
        with open(filterfile, 'r') as fh:
            filter_list = [line.strip() for line in fh]
        # always keep the 'Gene' column
        filter_list.append('Gene')
        # include only the columns in the filter list
        pan = pan.loc[:, pan.columns.isin(filter_list)]
    return pan


def blast_to_string(good_blast_hit, perfect_match, expected_neighbors, found_neighbors, overlap_found, overlap_gf, query_gf, long_distance, pangenome_status):
    # use part 1 of the string to describe the blast hit type
    # use part 2 of the string to describe the overlap
    # use part 3 of the string to describe the neighbor status

    blast_str = 'Missing'
    if good_blast_hit == True:
        blast_str = 'Present'
        if perfect_match == True:
            blast_str = 'Perfect'

    overlap_str = 'OVnone'
    if overlap_found == True:
        overlap_str = 'OVgene'
        if overlap_gf != None:
            if overlap_gf == query_gf:
                overlap_str = 'OVexpected'
            else:
                gf_number  = overlap_gf.split('_')[-1]
                overlap_str = f'OVg{gf_number}'

    neighbor_str = f'e{expected_neighbors}f{found_neighbors}'
    if long_distance == True:
        neighbor_str += 'l'

    pangenome_str = 'DIS'
    if pangenome_status == 'present' and good_blast_hit == True and overlap_str == 'OVexpected':
        pangenome_str = 'CON'
    # refound genes will not have an overlap due to the original gff being used for this step
    if pangenome_status == 'refound' and good_blast_hit == True and overlap_str == 'OVnone':
        pangenome_str = 'CON'
    if pangenome_status == 'absent' and good_blast_hit == False:
        pangenome_str = 'CON'

    return f'{pangenome_str}_{blast_str}_{overlap_str}_{neighbor_str}'


def make_blast_summary_matrix(panaroo_file, blast_file, output_file, filterfile=None):
    # generate a summary matrix where rows are gene families and columns are isolates
    # each cell contains a string that describes the blast search result

    # read in the panaroo presence/absence matrix
    pandf = read_panaroo_data(panaroo_file, None)
    # read in the blast results
    blastdf = pd.read_csv(blast_file, sep='\t', keep_default_na=False)

    # if a filter file is present, subset pandf to only include those columns
    if filterfile is not None:
        with open(filterfile, 'r') as fh:
            filter_list = [line.strip() for line in fh]
        # always keep the 'Gene' column
        filter_list.append('Gene')
        pandf = pandf.loc[:, pandf.columns.isin(filter_list)]

    # create a new dataframe with the same rows and columns as pandf, but with 'NOT_SEARCHED' in each cell
    summary_matrix = pd.DataFrame('NOT_SEARCHED', index=pandf.index, columns=pandf.columns)
    summary_matrix['Gene'] = pandf['Gene']

    # iterate through the blastdf and replace the values in summary_matrix
    for index, row in blastdf.iterrows():
        # convert any instances of 'True', 'False', or 'None' to their boolean equivalents
        row = row.replace({'True': True, 'False': False, 'None': None})
        gene_fam = row['Query_SeqID']
        isolate = row['Subject_SeqID']
        # use pandf to determine if an absence or presence was expected
        pangenome_status = 'present'
        pangenome_value = pandf.loc[pandf['Gene'] == gene_fam, isolate].values[0]
        if pangenome_value == '':
            pangenome_status = 'absent'
        elif 'refound' in pangenome_value:
            pangenome_status = 'refound'
        cell_data = blast_to_string(
            good_blast_hit = row['Good_Blast_Hit'],
            perfect_match = row['Perfect_Match'],
            expected_neighbors = row['Expected_Neighbors'],
            found_neighbors = row['Max_Neighbors_in_BLAST'],
            overlap_found = row['Overlap_Found'],
            overlap_gf = row['Overlap_GeneFamily'],
            query_gf = gene_fam,
            long_distance = row['Long_Distance'],
            pangenome_status = pangenome_status
        )
        summary_matrix.loc[summary_matrix['Gene'] == gene_fam, isolate] = cell_data

    # write the summary_matrix to output_file
    summary_matrix.to_csv(output_file, sep='\t', index=False)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        '--blast','-b',type=str,
        help='''Provide a BLAST summary file generated by the read_blast script.''',
        required=True
        )
    parser.add_argument(
        '--panaroo','-p',type=str,
        help='''Provide Panaroo presence/absence matrix file in the csv format. This should be the same file the gene families in the 
        input list are drawn from, and the same file used with extract_gene_from_isolate. Gene names should be present in this file.''',
        required=True
        )
    parser.add_argument(
        '--output','-o',type=str,
        help='''Provide a file name for the output file.''',
        required=True
        )
    parser.add_argument(
        '--filterfile','-f',type=str,
        help='''Provide a file name for a filter file. This should be a text file with one isolate name per line. Only isolates in this list will be included in the output matrix.''',
        required=False
        )
    args = parser.parse_args()
    make_blast_summary_matrix(args.panaroo, args.blast, args.output, args.filterfile)


if __name__ == '__main__':
    main()